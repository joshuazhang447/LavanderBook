// Builds src/lib/privacy-policy.ts from docs/privacy-policy.md, so the policy
// is written once: the Markdown is what moves to the main site later, and the
// app shows exactly the same words until then.
//
//   node scripts/build-privacy-policy.mjs
//
// Understands the little the policy uses: "# " title, "_Last updated: ..._",
// "## " sections, paragraphs, "- " lists (continued by indented lines),
// **bold**. A "> " note is the draft banner and is left out; so is everything
// after the first "---", which is the editors' checklist.

import fs from 'node:fs';

const source = fs.readFileSync('docs/privacy-policy.md', 'utf8').replace(/\r\n/g, '\n');
const body = source.split(/\n---\n/)[0];

let title = '';
let updated = '';
const intro = [];
const sections = [];
let blocks = intro;
let paragraph = null;
let list = null;

function endParagraph() {
  if (paragraph) blocks.push({ kind: 'p', text: paragraph.join(' ') });
  paragraph = null;
}
function endList() {
  if (list) blocks.push({ kind: 'list', items: list });
  list = null;
}

for (const raw of body.split('\n')) {
  const line = raw.trimEnd();
  if (line.startsWith('>')) continue;
  if (line.startsWith('# ')) {
    title = line.slice(2).trim();
    continue;
  }
  const date = line.match(/^_Last updated: (.+)_$/);
  if (date) {
    updated = date[1].trim();
    continue;
  }
  if (line.startsWith('## ')) {
    endParagraph();
    endList();
    blocks = [];
    sections.push({ title: line.slice(3).trim(), blocks });
    continue;
  }
  if (line.startsWith('- ')) {
    endParagraph();
    list ??= [];
    list.push(line.slice(2).trim());
    continue;
  }
  if (list && /^\s{2,}\S/.test(line)) {
    list[list.length - 1] += ` ${line.trim()}`;
    continue;
  }
  if (line.trim() === '') {
    endParagraph();
    endList();
    continue;
  }
  endList();
  paragraph ??= [];
  paragraph.push(line.trim());
}
endParagraph();
endList();

if (!title || !updated || sections.length === 0) {
  throw new Error('docs/privacy-policy.md: missing the title, the date or the sections');
}
if (/\[To (decide|check)/.test(body)) {
  throw new Error('docs/privacy-policy.md still has a [To decide] or [To check] in it');
}

const out = `// GENERATED by scripts/build-privacy-policy.mjs from docs/privacy-policy.md.
// Edit the Markdown and run the script; never this file.

export type PolicyBlock = { kind: 'p'; text: string } | { kind: 'list'; items: string[] };
export type PolicySection = { title: string; blocks: PolicyBlock[] };

/** Inline **bold** is kept in the strings; the page draws it. */
export const PRIVACY_POLICY: {
  title: string;
  updated: string;
  intro: PolicyBlock[];
  sections: PolicySection[];
} = ${JSON.stringify({ title, updated, intro, sections }, null, 2)};
`;

fs.writeFileSync('src/lib/privacy-policy.ts', out);
console.log(`privacy policy: ${sections.length} sections, updated ${updated}`);
